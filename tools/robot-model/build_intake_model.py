#!/usr/bin/env python3
"""Generate a schematic sliding intake; dimensions are provisional, not measured CAD."""
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSET = ROOT / "visualization/advantagescope/Robot_SIMCITY_3464_2026"
RETRACTED = (-0.38, 0.0, 0.18)
TRAVEL = 0.30


def build():
    config = json.loads((ASSET / "config.json").read_text())
    assert config["rotations"] == [{"axis": "z", "degrees": 90}]
    offset = config["position"]
    vertices, normals = [], []
    # Two rails and a bright crossbar represent the translating roller carriage.
    # Export in the same CAD frame as the existing model so its default pose also aligns.
    for center, size in [
        ((0.08, -0.25, 0), (0.24, 0.035, 0.045)),
        ((0.08, 0.25, 0), (0.24, 0.035, 0.045)),
        ((-0.04, 0, 0), (0.075, 0.54, 0.075)),
    ]:
        for axis in range(3):
            u, v = (axis + 1) % 3, (axis + 2) % 3
            for sign in (-1, 1):
                corners = []
                for a, b in [(-1, -1), (1, -1), (1, 1), (-1, 1)]:
                    point = list(center)
                    point[axis] += sign * size[axis] / 2
                    point[u] += a * size[u] / 2
                    point[v] += b * size[v] / 2
                    robot = [point[i] + RETRACTED[i] - offset[i] for i in range(3)]
                    corners.append((robot[1], -robot[0], robot[2]))
                normal = [0, 0, 0]
                normal[axis] = sign
                normal = (normal[1], -normal[0], normal[2])
                indices = (0, 1, 2, 0, 2, 3) if sign == 1 else (0, 2, 1, 0, 3, 2)
                for index in indices:
                    vertices.append(corners[index])
                    normals.append(normal)
    positions = b"".join(struct.pack("<fff", *v) for v in vertices)
    binary = positions + b"".join(struct.pack("<fff", *n) for n in normals)
    asset = {
        "asset": {"version": "2.0", "generator": "Schematic intake timing visualization"},
        "scene": 0, "scenes": [{"nodes": [0]}],
        "nodes": [{"mesh": 0, "name": "SIM schematic intake NOSIMPLIFY"}],
        "meshes": [{"primitives": [{"attributes": {"POSITION": 0, "NORMAL": 1}, "material": 0}]}],
        "materials": [{"name": "Provisional intake orange", "pbrMetallicRoughness": {
            "baseColorFactor": [1.0, 0.32, 0.03, 1.0], "metallicFactor": 0.0, "roughnessFactor": 0.7}}],
        "buffers": [{"byteLength": len(binary)}],
        "bufferViews": [{"buffer": 0, "byteOffset": 0, "byteLength": len(positions)},
                        {"buffer": 0, "byteOffset": len(positions), "byteLength": len(binary)-len(positions)}],
        "accessors": [
            {"bufferView": 0, "componentType": 5126, "count": len(vertices), "type": "VEC3",
             "min": [min(v[i] for v in vertices) for i in range(3)],
             "max": [max(v[i] for v in vertices) for i in range(3)]},
            {"bufferView": 1, "componentType": 5126, "count": len(normals), "type": "VEC3"}],
    }
    header = json.dumps(asset, separators=(",", ":")).encode()
    header += b" " * (-len(header) % 4)
    glb = struct.pack("<III", 0x46546C67, 2, 28 + len(header) + len(binary))
    glb += struct.pack("<II", len(header), 0x4E4F534A) + header
    glb += struct.pack("<II", len(binary), 0x004E4942) + binary
    (ASSET / "model_2.glb").write_bytes(glb)
    config["components"] = config["components"][:2] + [{
        "zeroedRotations": config["rotations"],
        "zeroedPosition": [offset[i] - RETRACTED[i] for i in range(3)],
    }]
    (ASSET / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    java = ROOT / "visualization/src/main/java/frc/robot/visualization/IntakeModelGeometry.java"
    java.write_text('''package frc.robot.visualization;

import edu.wpi.first.math.geometry.Translation3d;

/**
 * Provisional schematic dimensions, generated by build_intake_model.py; not hardware calibration.
 */
public final class IntakeModelGeometry {
  private IntakeModelGeometry() {}

  public static final Translation3d RETRACTED_POSITION = new Translation3d(%s);
  public static final double TRAVEL_METERS = %s;
}
''' % (", ".join(str(v) for v in RETRACTED), TRAVEL))
    print("Generated schematic model_2.glb, component configuration, and IntakeModelGeometry.java")


if __name__ == "__main__":
    build()
